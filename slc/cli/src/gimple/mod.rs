//! `slc gimple`: translates GCC's optimized GIMPLE dumps into the
//! normalized form of `layers/gimple.sl` (an SL layer with one `Function`
//! per GIMPLE function).
//!
//!   slc gimple --elf ELF --obj FILE.o --source NAME.c DUMP.optimized -o OUT.sl
//!
//! FILE.o is the source compiled with -g (struct layouts from its DWARF),
//! ELF the linked binary (addresses of globals), NAME.c the source file's
//! name (to find its static symbols). `scripts/dump-gimple.sh` produces the
//! dump and the object.

mod dump;
mod dwarf;
mod lower;

use crate::commands::CResult;

pub fn gimple(args: &[String]) -> CResult {
    let (mut elf, mut obj, mut source, mut out, mut dump_path) = (None, None, None, None, None);
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--elf" => elf = it.next().cloned(),
            "--obj" => obj = it.next().cloned(),
            "--source" => source = it.next().cloned(),
            "-o" => out = it.next().cloned(),
            other => dump_path = Some(other.to_string()),
        }
    }
    let usage = "usage: slc gimple --elf ELF --obj FILE.o --source NAME.c DUMP.optimized -o OUT.sl";
    let (elf, obj, source, out, dump_path) = match (elf, obj, source, out, dump_path) {
        (Some(e), Some(o), Some(s), Some(t), Some(d)) => (e, o, s, t, d),
        _ => return Err(usage.into()),
    };
    let text = std::fs::read_to_string(&dump_path).map_err(|e| format!("{}: {}", dump_path, e))?;
    let funcs = dump::parse_dump(&text).map_err(|e| format!("{}: {}", dump_path, e))?;
    let dw = dwarf::Dwarf::from_object(&obj)?;
    let anchors: Vec<String> = funcs.iter().map(|f| f.name.clone()).collect();
    let syms = lower::Symbols::read(&elf, &source, &anchors)?;
    let mut callees = lower::Callees::default();
    let mut bodies = Vec::new();
    let mut failed = Vec::new();
    {
        let mut lw = lower::Lower { dw: &dw, syms: &syms, callees: &mut callees };
        for f in &funcs {
            match lw.function(f) {
                Ok(s) => bodies.push(s),
                Err(e) => failed.push(format!("{}: {}", f.name, e)),
            }
        }
    }
    let module: String = std::path::Path::new(&dump_path)
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("gimple")
        .split(".c.")
        .next()
        .unwrap()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    let mut s = String::new();
    s.push_str(&format!("layer gimple_{} uses gimple, abi, x86_64_linux\n\n", module));
    s.push_str(&format!("// Generated by `slc gimple` from {} (types: {}, addresses: {}).\n", dump_path, obj, elf));
    s.push_str("// Functions call their callees by number:\n");
    for (i, n) in callees.names.iter().enumerate() {
        s.push_str(&format!("const CALLEE_{}: nat = {}\n", n.trim_start_matches('.'), i));
    }
    s.push_str("\nfn ty(p: nat, s: bool) -> Ty = Ty { prec: p, signed: s }\n\n");
    s.push_str(&bodies.join("\n"));
    std::fs::write(&out, s).map_err(|e| format!("{}: {}", out, e))?;
    println!("{}: {} of {} functions translated", out, bodies.len(), funcs.len());
    for f in &failed {
        println!("  not translated: {}", f);
    }
    if failed.is_empty() { Ok(()) } else { Err("some functions could not be translated".into()) }
}
