//! `slc steps`: per-instruction step theorems for functions of a binary.
//!
//!   slc steps ELF CLAIM.core SYMBOL... -o OUT.core
//!
//! For every distinct instruction encoding in the functions: a theorem
//! that a machine whose bytes at `rip` are the encoding's runs `step()` as
//! `exec_insn(len, insn)` of its one decoding -- for any `rip` and any
//! state. The theorem's hypotheses are the bytes the decoder reads (the
//! instruction's own, unless some row looks further). Exclusivity (no other
//! row matches) is shown once, here, by the evaluator: in the theorem's
//! proof (`members`). The instruction boundaries come from the untrusted
//! interpreter; a wrong one only makes a theorem fail or go unused.
//!
//! Then, per function `F` (its bytes `F.code`, loaded at its address):
//! for the instruction at each address A, `F.at_A` (with the code loaded
//! and `rip = A`, a step runs the instruction's body: its fetch succeeds)
//! and `F.ok_A`, its outcome when its memory accesses succeed (given as
//! hypotheses `all i < n. can_access(vm, a + i, k)`): the successor state,
//! the code still loaded. The successor state is computed here by the
//! simplifier (untrusted use: it only proposes the statement); the file
//! proves it. A simulation of the function then chains these outcomes, one
//! path per instruction, instead of expanding each instruction's semantics
//! with all its fault cases.

use crate::commands::{load_spec_globals, CResult};
use sl_interp::elf::Elf;
use sl_interp::Interp;
use sl_kernel::syntax::{self, parse_term, Printer};
use sl_kernel::{Env, Term};
use std::collections::BTreeMap;
use std::fmt::Write;

const BYTES: &str = "app(app(app(m, \"vm\"), \"bytes\"), bits_add(64, app(m, \"rip\"), {k}))";
const DECODED: &str = "fn_build(omega, i. app(app(app(m, \"vm\"), \"bytes\"), bits_add(64, app(m, \"rip\"), bits_of_int(64, i))))";

fn byte_eq(k: usize, v: u8) -> String {
    format!("{} = {}", BYTES.replace("{k}", &k.to_string()), v)
}

pub fn steps(args: &[String]) -> CResult {
    let (mut out, mut pos) = (None, Vec::new());
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "-o" => out = it.next().cloned(),
            _ => pos.push(a.clone()),
        }
    }
    let usage = "usage: slc steps ELF CLAIM.core SYMBOL... -o OUT.core";
    let (Some(out), true) = (out, pos.len() >= 3) else { return Err(usage.into()) };
    let (elf_path, claim) = (&pos[0], &pos[1]);
    let elf = Elf::parse(std::fs::read(elf_path).map_err(|e| e.to_string())?)?;
    // instruction boundaries (untrusted: the interpreter's decoder)
    let mut sm = sl_syntax::SourceMap::default();
    let g = load_spec_globals(&mut sm)?;
    let interp = Interp::new(&g, "x86")?;
    // encoding (with the 15 bytes at its first address) -> addresses
    let mut encodings: BTreeMap<Vec<u8>, (Vec<u8>, Vec<u64>)> = BTreeMap::new();
    for s in &pos[2..] {
        let sym = elf.symbol(s).ok_or_else(|| format!("no symbol `{}`", s))?;
        let mut addr = sym.value;
        while addr < sym.value + sym.size {
            let window = elf.bytes_at(addr, 15).unwrap_or(&[]).to_vec();
            let len = interp.decode(&window).first().map(|m| m.len).ok_or_else(|| format!("{:x}: not decoded", addr))?;
            let e = encodings.entry(window[..len].to_vec()).or_insert((window.clone(), Vec::new()));
            e.1.push(addr);
            addr += len as u64;
        }
    }
    // the logic: prelude, library, the claim's definitions
    let mut env = Env::new();
    let mut prover = sl_proof::ScriptProver;
    for (i, f) in ["core/prelude.core", "core/logic.core", "core/sets.core", claim.as_str()].iter().enumerate() {
        let src = std::fs::read_to_string(f).map_err(|e| format!("{}: {}", f, e))?;
        syntax::load_with(&mut env, &src, i == 0, Some(&mut prover)).map_err(|e| format!("{}: {}", f, e.0))?;
    }
    let lg = sl_kernel::ext::Logic::new(&env).map_err(|e| e.0)?;
    let m = env.new_var("m", 0);
    let scope = vec![("m".to_string(), m)];
    let set = parse_term(&mut env, &format!("x86_64_linux.x86.decode({})", DECODED), &scope).map_err(|e| e.0)?;
    let mut s = String::new();
    writeln!(s, "// Generated by `slc steps` from {} ({}): step theorems, one per", elf_path, pos[2..].join(", ")).unwrap();
    writeln!(s, "// instruction encoding; per function, where a step from each instruction").unwrap();
    writeln!(s, "// goes and its outcome. Check after core/prelude.core, core/logic.core,").unwrap();
    writeln!(s, "// core/sets.core, core/nat.core, core/records.core, {}, proofs/x86.core", claim).unwrap();
    writeln!(s, "// and proofs/x86_code.core.\n").unwrap();
    let mut failed = Vec::new();
    let mut theorems: BTreeMap<Vec<u8>, StepInfo> = BTreeMap::new();
    for (enc, (window, addrs)) in &encodings {
        // the instruction's own bytes, else all 15
        let mut known = None;
        for n in [enc.len(), window.len()] {
            let eqs: Vec<Term> = (0..n).map(|k| parse_term(&mut env, &byte_eq(k, window[k]), &scope)).collect::<Result<_, _>>().map_err(|e| e.0)?;
            match lg.eval_members(&env, &set, &eqs) {
                Ok((fact, used)) => {
                    known = Some((fact, used));
                    break;
                }
                Err(e) if n == window.len() => failed.push(format!("{}: {}", hex(enc), e.0)),
                Err(_) => {}
            }
        }
        let Some((fact, used)) = known else { continue };
        let Some(member) = one_member(&fact) else {
            failed.push(format!("{}: not exactly one decoding", hex(enc)));
            continue;
        };
        let pr = Printer::new(&env);
        let c = pr.term(&member);
        let (len, insn) = match member.node() {
            sl_kernel::Node::App(_, p) if p.len() == 2 => (pr.term(&p[0]), pr.term(&p[1])),
            _ => {
                failed.push(format!("{}: decoding not a pair", hex(enc)));
                continue;
            }
        };
        let bytes: Vec<(usize, u8)> = used.iter().map(|&k| (k, window[k])).collect();
        let name = format!("x86.step_{}", bytes.iter().map(|(_, b)| format!("{:02x}", b)).collect::<String>());
        let hyps: Vec<String> = bytes.iter().map(|(k, v)| byte_eq(*k, *v)).collect();
        let hnames: Vec<String> = bytes.iter().map(|(k, _)| format!("h{}", k)).collect();
        let dec = format!("x86_64_linux.x86.decode({})", DECODED);
        let addrs: Vec<String> = addrs.iter().map(|a| format!("{:x}", a)).collect();
        writeln!(s, "// {} at {}", hex(enc), addrs.join(", ")).unwrap();
        writeln!(s, "theorem {}(m, o):", name).unwrap();
        writeln!(s, "  {} ->", hyps.join(" ->\n  ")).unwrap();
        writeln!(s, "  runs(x86_64_linux.step(), m, o) -> runs(x86_64_linux.exec_insn({}, {}), m, o)", len, insn).unwrap();
        writeln!(s, "proof").unwrap();
        for (h, e) in hnames.iter().zip(&hyps) {
            writeln!(s, "  assume {}: {}", h, e).unwrap();
        }
        writeln!(s, "  assume h: runs(x86_64_linux.step(), m, o)").unwrap();
        writeln!(s, "  have d := members({{{}}}, {})", dec, hnames.join(", ")).unwrap();
        writeln!(s, "  have d1: all x. x in {} -> x = {} proof\n    fix x\n    show by simp(expand(all_elim(d, {{x}}), iff))\n  qed", dec, c).unwrap();
        writeln!(s, "  have dc: {c} in {d} by simp(expand(all_elim(d, {{{c}}}), iff))", c = c, d = dec).unwrap();
        writeln!(s, "  have ne0: {} = empty -> false proof\n    assume e: {} = empty\n    show by taut(rewrite(e, dc), empty_mem[x := {}])\n  qed", dec, dec, c).unwrap();
        writeln!(s, "  have ne: !({} = empty) by taut(ne0)", dec).unwrap();
        writeln!(s, "  have ty: {} in cart(omega, univ(1)) by eval()", c).unwrap();
        writeln!(s, "  show by simp(h, d1, dc, ne, ty, keep(x86_64_linux.exec_insn))").unwrap();
        writeln!(s, "qed\n").unwrap();
        theorems.insert(enc.clone(), StepInfo { name: name.clone(), bytes: bytes.clone(), len: len.clone(), insn: insn.clone() });
    }
    // per function: its code, and for each instruction what a step from it
    // does (`at_`) and its outcome when its memory accesses succeed (`ok_`)
    let mut outcomes = 0;
    for sname in &pos[2..] {
        let sym = elf.symbol(sname).ok_or_else(|| format!("no symbol `{}`", sname))?;
        let code = elf.bytes_at(sym.value, sym.size as usize).ok_or_else(|| format!("{}: no bytes", sname))?.to_vec();
        let base = sym.value;
        let ns = sname.as_str();
        writeln!(s, "// ----------------------------------------------------------------------\n// {}: its instructions, at {:x}\n", ns, base).unwrap();
        writeln!(s, "def {}.code() := bytes_seq(bytes\"{}\")\n", ns, code.iter().map(|b| format!("{:02x}", b)).collect::<String>()).unwrap();
        let mut addr = base;
        while addr < base + sym.size {
            let window = elf.bytes_at(addr, 15).unwrap_or(&[]).to_vec();
            let len = interp.decode(&window).first().map(|m| m.len).ok_or_else(|| format!("{:x}: not decoded", addr))?;
            let enc = window[..len].to_vec();
            if let Some(info) = theorems.get(&enc) {
                s.push_str(&at_lemma(ns, base, addr, info));
                match ok_lemma(&mut env, &lg, ns, base, addr, info) {
                    Ok(Some(t)) => {
                        s.push_str(&t);
                        outcomes += 1;
                    }
                    Ok(None) => failed.push(format!("{:x}: no successful outcome", addr)),
                    Err(e) => failed.push(format!("{:x}: outcome: {}", addr, e)),
                }
            }
            addr += len as u64;
        }
    }
    std::fs::write(&out, &s).map_err(|e| format!("{}: {}", out, e))?;
    let n: usize = encodings.values().map(|(_, a)| a.len()).sum();
    println!("{}: {} instructions, {} distinct encodings, {} theorems, {} outcomes", out, n, encodings.len(), theorems.len(), outcomes);
    for f in &failed {
        println!("  no theorem: {}", f);
    }
    Ok(())
}

/// What the step theorem of an encoding says: its name, the bytes it reads
/// (offset, value), and the decoded instruction (length, term).
struct StepInfo {
    name: String,
    bytes: Vec<(usize, u8)>,
    len: String,
    insn: String,
}

/// `NS.at_ADDR`: from `rip = ADDR`, with the function's code loaded at
/// `base`, a step runs the instruction's body (its fetch succeeds).
fn at_lemma(ns: &str, base: u64, addr: u64, info: &StepInfo) -> String {
    let mut s = String::new();
    let hdr = hdr(ns, base, addr);
    writeln!(s, "theorem {}.at_{:x}: {}runs(x86_64_linux.exec_body({}, {}), m, o)", ns, addr, hdr, info.len, info.insn).unwrap();
    writeln!(s, "proof\n  fix m\n  fix o\n  assume h: runs(x86_64_linux.step(), m, o)").unwrap();
    writeln!(s, "  assume hc: abi.code_at(app(m, \"vm\"), {}, {}.code())\n  assume hr: app(m, \"rip\") = {}", base, ns, addr).unwrap();
    writeln!(s, "  have c := expand(expand(hc, abi.code_at), {}.code)", ns).unwrap();
    let mut e = format!("{}[m := m, o := o]", info.name);
    for (k, v) in &info.bytes {
        writeln!(s, "  have b{k} := simp(all_elim(c, {{{}}}))", addr - base + *k as u64, k = k).unwrap();
        writeln!(s, "  have hb{k}: {} by simp(hr, b{k})", byte_eq(*k, *v), k = k).unwrap();
        e = format!("mp({}, hb{})", e, k);
    }
    writeln!(s, "  have e := mp({}, h)", e).unwrap();
    writeln!(
        s,
        "  have cf: all i. i in omega -> int_lt(i, {len}) -> x86_64_linux.fetchable(app(m, \"vm\"), bits_add(64, {a}, bits_of_int(64, i))) by simp(expand(all_elim(all_elim(all_elim(all_elim(all_elim(x86.code_fetch, {{app(m, \"vm\")}}), {{{b}}}), {{{ns}.code()}}), {{{a}}}), {{{len}}}), {ns}.code), expand(hc, {ns}.code))",
        len = info.len, a = addr, b = base, ns = ns
    )
    .unwrap();
    writeln!(s, "  show by simp(e, hr, cf, x86.touch_range_fetch, keep(x86_64_linux.step, x86_64_linux.exec_body, x86_64_linux.touch_range))\nqed\n").unwrap();
    s
}

/// The hypotheses common to the lemmas about the instruction at `addr`.
fn hdr(ns: &str, base: u64, addr: u64) -> String {
    format!("all m o. runs(x86_64_linux.step(), m, o) -> abi.code_at(app(m, \"vm\"), {}, {}.code()) -> app(m, \"rip\") = {} -> ", base, ns, addr)
}

/// `NS.ok_ADDR`: the outcome of the instruction at `addr` when its memory
/// accesses succeed -- the successor state, as computed by the simplifier
/// from the instruction's body (each `touch_range` of a data access taken
/// to change nothing, which `x86.touch_range_access` justifies given the
/// access; the canonical-address checks follow from the access too). Several
/// outcomes (e.g. a conditional jump) are a disjunction, each with its
/// conditions; values the model leaves open are existential. The statement
/// is proposed here and proven in the file (checked by the kernel).
fn ok_lemma(env: &mut Env, lg: &sl_kernel::ext::Logic, ns: &str, base: u64, addr: u64, info: &StepInfo) -> Result<Option<String>, String> {
    use sl_kernel::Node;
    let m = env.vars.iter().position(|v| v.name == "m").map(|i| i as u32).unwrap_or_else(|| env.new_var("m", 0));
    let o = env.vars.iter().position(|v| v.name == "o").map(|i| i as u32).unwrap_or_else(|| env.new_var("o", 0));
    let scope = vec![("m".to_string(), m), ("o".to_string(), o)];
    let mut prem = vec![format!("runs(x86_64_linux.exec_body({}, {}), m, o)", info.len, info.insn), format!("app(m, \"rip\") = {}", addr)];
    for r in 0..16 {
        prem.push(format!("app(app(m, \"gpr\"), {}) in bits(64)", r));
    }
    let prem: Vec<Term> = prem.iter().map(|p| parse_term(env, p, &scope)).collect::<Result<_, _>>().map_err(|e| e.0)?;
    let sym = |n: &str| env.sym_by_name.get(n).copied().ok_or_else(|| format!("no `{}`", n));
    let (touch, runs, ok, eq) = (sym("x86_64_linux.touch_range")?, sym("runs")?, sym("ok")?, env.builtins.eq);
    let paths = lg.simp_paths(env, &prem, &[touch]).map_err(|e| e.0)?;
    let bf = env.binders_fn();
    let pr = Printer::new(env);
    let mut alts: Vec<String> = Vec::new();
    let mut accesses: Vec<(String, String, String)> = Vec::new();
    for (vars, lits) in &paths {
        // the outcome `o = ok(X, E)`
        let Some(out) = lits.iter().find_map(|l| match l.node() {
            Node::App(e, a) if *e == eq && matches!(a[0].node(), Node::Var(v, x) if *v == o && x.is_empty()) => match a[1].node() {
                Node::App(k, b) if *k == ok => Some(b[0].clone()),
                _ => None,
            },
            _ => None,
        }) else {
            continue;
        };
        // the data accesses: `runs(touch_range(A, N, K), S, ok(Y, Z))`,
        // with Y := S, Z := empty
        let mut out = out;
        let mut conds: Vec<Term> = Vec::new();
        let mut subst: Vec<(u32, Term)> = Vec::new();
        let mut touched: Vec<(Term, Term, Term)> = Vec::new();
        for l in lits {
            if let Node::App(r, a) = l.node() {
                if *r == runs {
                    if let (Node::App(t, ta), Node::App(k, kb)) = (a[0].node(), a[2].node()) {
                        if *t == touch && *k == ok {
                            touched.push((ta[0].clone(), ta[1].clone(), ta[2].clone()));
                            if let Node::Var(y, _) = kb[0].node() {
                                subst.push((*y, a[1].clone()));
                            }
                            if let Node::Var(z, _) = kb[1].node() {
                                subst.push((*z, Term::app(env.sym_by_name["empty"], vec![])));
                            }
                            continue;
                        }
                    }
                }
            }
            conds.push(l.clone());
        }
        // (a touch may start from the state an earlier one left -- a read,
        // then a write: the substitution resolved to a fixpoint)
        for _ in 0..subst.len() {
            let snapshot = subst.clone();
            for (_, t) in subst.iter_mut() {
                for (v, u) in &snapshot {
                    *t = t.subst_var(*v, u, &bf);
                }
            }
        }
        for (a, n, k) in &touched {
            let mut a = a.clone();
            for (v, t) in &subst {
                a = a.subst_var(*v, t, &bf);
            }
            let a = lg.simp_term(env, &a);
            accesses.push((pr.term(&a), pr.term(n), pr.term(k)));
        }
        for (v, t) in &subst {
            out = out.subst_var(*v, t, &bf);
        }
        let out = lg.simp_term(env, &out);
        // conditions: what is left but the premises, the outcome, typing and
        // the canonical-address checks
        // (a choice the model leaves open, `t = false` / `t = true` for t of
        // the path's own values: either, so the paths of the choices merge)
        let false_ = env.sym_by_name.get("false").copied();
        let open_choice = |c: &Term| -> Option<Term> {
            let Node::App(e, a) = c.node() else { return None };
            if *e != eq {
                return None;
            }
            let is_bool = |t: &Term| matches!(t.node(), Node::App(f, x) if x.is_empty() && (Some(*f) == false_ || env.syms[*f as usize].name == "true"));
            let mut vs = Vec::new();
            a[0].vars(&mut vs);
            (is_bool(&a[1]) && vs.iter().any(|v| vars.contains(v))).then(|| a[0].clone())
        };
        let conds: Vec<String> = conds
            .iter()
            .map(|c| {
                let mut c = c.clone();
                for (v, t) in &subst {
                    c = c.subst_var(*v, t, &bf);
                }
                match open_choice(&c) {
                    Some(t) => {
                        let t = pr.term(&t);
                        format!("{} = false || {} = true", t, t)
                    }
                    None => pr.term(&c),
                }
            })
            .filter(|c| !c.starts_with("o = ") && !c.contains("canonical") && !c.ends_with(" in bits(64)") && !prem.iter().any(|p| pr.term(p) == *c))
            .map(|c| format!("({})", c))
            .collect();
        let x = pr.term(&out);
        let mut body = conds.clone();
        body.push(format!("o = ok({}, empty)", x));
        body.push(format!("abi.code_at(app({}, \"vm\"), {}, {}.code())", x, base, ns));
        let mut alt = body.join(" && ");
        // values left open: existential (the path's own variables, named by
        // their order, so that paths alike are alike in text)
        let mut k = 0;
        for v in vars {
            let name = format!("?v{}", v);
            if alt.contains(&name) {
                alt = format!("ex u{k}. {}", alt.replace(&name, &format!("u{}", k)));
                k += 1;
            }
        }
        let alt = format!("({})", alt);
        if !alts.contains(&alt) {
            alts.push(alt);
        }
    }
    if alts.is_empty() {
        return Ok(None);
    }
    accesses.sort();
    accesses.dedup();
    // typing of the registers the statement reads
    let text = format!("{} {:?}", alts.join(" "), accesses);
    let regs: Vec<u32> = (0..16).filter(|r| text.contains(&format!("app(app(m, \"gpr\"), {})", r))).collect();
    let mut s = String::new();
    write!(s, "theorem {}.ok_{:x}: {}", ns, addr, hdr(ns, base, addr)).unwrap();
    for r in &regs {
        write!(s, "app(app(m, \"gpr\"), {}) in bits(64) -> ", r).unwrap();
    }
    let acc = |(a, n, k): &(String, String, String)| format!("(all i. i in omega -> int_lt(i, {n}) -> x86_64_linux.can_access(app(m, \"vm\"), bits_add(64, {a}, bits_of_int(64, i)), {k}))");
    for a in &accesses {
        write!(s, "{} -> ", acc(a)).unwrap();
    }
    writeln!(s, "\n  {}", alts.join(" || ")).unwrap();
    writeln!(s, "proof\n  fix m\n  fix o\n  assume h: runs(x86_64_linux.step(), m, o)").unwrap();
    writeln!(s, "  assume hc: abi.code_at(app(m, \"vm\"), {}, {}.code())\n  assume hr: app(m, \"rip\") = {}", base, ns, addr).unwrap();
    let mut facts = String::new();
    for r in &regs {
        writeln!(s, "  assume t{r}: app(app(m, \"gpr\"), {r}) in bits(64)").unwrap();
        write!(facts, "t{}, ", r).unwrap();
    }
    for (j, a) in accesses.iter().enumerate() {
        let (ad, n, k) = a;
        writeln!(s, "  assume a{j}: {}", acc(a)).unwrap();
        writeln!(s, "  have k{j}: all i. i in omega -> int_lt(i, {n}) -> x86_64_linux.canonical(bits_add(64, {ad}, bits_of_int(64, i))) proof\n    fix i\n    assume i1: i in omega\n    assume i2: int_lt(i, {n})\n    show by mp(all_elim(all_elim(all_elim(x86.access_canonical, {{app(m, \"vm\")}}), {{bits_add(64, {ad}, bits_of_int(64, i))}}), {{{k}}}), mp(mp(all_elim(a{j}, {{i}}), i1), i2))\n  qed").unwrap();
        write!(facts, "a{j}, k{j}, ").unwrap();
    }
    writeln!(s, "  have e := mp(mp(mp(all_elim(all_elim({}.at_{:x}, {{m}}), {{o}}), h), hc), hr)", ns, addr).unwrap();
    writeln!(
        s,
        "  show by simp(e, hc, hr, {facts}all_elim(all_elim(x86.store_code, {{{b}}}), {{{ns}.code()}}), all_elim(all_elim(x86.touch_range_code, {{{b}}}), {{{ns}.code()}}), x86.touch_range_access, keep(x86_64_linux.touch_range, abi.code_at, {ns}.code, x86_64_linux.can_access))\nqed\n",
        b = base
    )
    .unwrap();
    Ok(Some(s))
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{:02x}", x)).collect::<Vec<_>>().join(" ")
}

/// `all x. x in S <-> x = c` -> c
fn one_member(fact: &Term) -> Option<Term> {
    use sl_kernel::Node;
    let Node::App(_, a) = fact.node() else { return None };
    let Node::App(_, iff) = a[0].node() else { return None };
    let Node::App(_, eq) = iff.get(1)?.node() else { return None };
    match eq.get(1) {
        Some(c) if matches!(eq[0].node(), Node::BVar(0)) => Some(c.clone()),
        _ => None,
    }
}
